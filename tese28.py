# Function คือ การทำงานหนึ่งๆ จะไม่ทำงานหากไม่เรียกใช้ (call function) ได้

# Function มีที่มาที่ไปยังบ้าง
# - Standard Function/Built-in Function มากับโปรแกรม
# - User Define Function ฟังก์ชั่นที่ Dev ตั้งขึ้นมาเอง
# - Third-party Function ฟังก์ชั่นที่ไม่ใช่ Dev ที่ตั้งขึ้นมาเอง

# Function มี 4 ประเภท
# - on parameter no return
# - have parameter no return
# - on parameter have return
# - have parameter have return